package com.iamyuvraj0.vela.lyrics

import android.content.Context
import com.iamyuvraj0.vela.kugou.KuGou
import com.iamyuvraj0.vela.constants.EnableKugouKey
import com.iamyuvraj0.vela.utils.dataStore
import com.iamyuvraj0.vela.utils.get

object KuGouLyricsProvider : LyricsProvider {
    override val name = "Kugou"
    override fun isEnabled(context: Context): Boolean =
        context.dataStore[EnableKugouKey] ?: true

    override suspend fun getLyrics(
        id: String,
        title: String,
        artist: String,
        album: String?,
        duration: Int,
    ): Result<String> = KuGou.getLyrics(title, artist, duration)

    override suspend fun getAllLyrics(
        id: String,
        title: String,
        artist: String,
        album: String?,
        duration: Int,
        callback: (String) -> Unit,
    ) {
        KuGou.getAllPossibleLyricsOptions(title, artist, duration, callback)
    }
}
