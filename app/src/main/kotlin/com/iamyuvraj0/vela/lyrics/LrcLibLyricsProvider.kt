package com.iamyuvraj0.vela.lyrics

import android.content.Context
import com.iamyuvraj0.vela.lrclib.LrcLib
import com.iamyuvraj0.vela.constants.EnableLrcLibKey
import com.iamyuvraj0.vela.utils.dataStore
import com.iamyuvraj0.vela.utils.get

object LrcLibLyricsProvider : LyricsProvider {
    override val name = "LrcLib"

    override fun isEnabled(context: Context): Boolean = context.dataStore[EnableLrcLibKey] ?: true

    override suspend fun getLyrics(
        id: String,
        title: String,
        artist: String,
        album: String?,
        duration: Int,
    ): Result<String> = LrcLib.getLyrics(title, artist, duration)

    override suspend fun getAllLyrics(
        id: String,
        title: String,
        artist: String,
        album: String?,
        duration: Int,
        callback: (String) -> Unit,
    ) {
        LrcLib.getAllLyrics(title, artist, duration, null, callback)
    }
}
